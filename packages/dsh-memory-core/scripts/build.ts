#!/usr/bin/env node
/**
 * Build the shared core package:
 *
 *   lib/index.js        Host helpers, bundled to one ESM file
 *   lib/client.js       browser form framework, bundled to one ESM file
 *   lib/types/**\/*.d.ts declarations for both entries
 */
import { execFileSync } from 'node:child_process';
import { rm } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const packageRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const require = createRequire(import.meta.url);
const libDir = join(packageRoot, 'lib');

await rm(libDir, { recursive: true, force: true });
execFileSync(process.execPath, [require.resolve('typescript/bin/tsc'), '-p', join(packageRoot, 'tsconfig.build.json')], {
    cwd: packageRoot,
    stdio: 'inherit',
});

await build({
    entryPoints: [join(packageRoot, 'src/index.ts')],
    outfile: join(libDir, 'index.js'),
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: 'node22',
    packages: 'external',
    sourcemap: false,
    charset: 'utf8',
    logLevel: 'warning',
    banner: { js: '// Generated by scripts/build.ts. Do not edit.' },
});

await build({
    entryPoints: [join(packageRoot, 'src/client/index.ts')],
    outfile: join(libDir, 'client.js'),
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2022',
    packages: 'external',
    sourcemap: false,
    charset: 'utf8',
    logLevel: 'warning',
    banner: { js: '// Generated by scripts/build.ts. Do not edit.' },
});

console.log('built lib/index.js, lib/client.js and lib/types');

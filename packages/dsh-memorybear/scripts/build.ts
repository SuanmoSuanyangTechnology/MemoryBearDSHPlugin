#!/usr/bin/env node
/**
 * Build the package in the layout dsh's own plugins use:
 *
 *   lib/index.js        Host half, bundled to one ESM file
 *   lib/client.js       browser half, bundled into dsh's lazy-CJS factory
 *   lib/types/**\/*.d.ts type declarations for both halves
 *
 * `@deepseek-ai/schemastery` and Node builtins stay external; React and
 * `react/jsx-runtime` are supplied by the dsh web client at runtime.
 */
import { execFileSync } from 'node:child_process';
import { readFile, rm, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const packageRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const require = createRequire(import.meta.url);
const pkg = JSON.parse(await readFile(join(packageRoot, 'package.json'), 'utf8')) as { name: string };
const libDir = join(packageRoot, 'lib');

await rm(libDir, { recursive: true, force: true });

// Declarations for both halves: lib/types/index.d.ts + lib/types/client/index.d.ts.
execFileSync(process.execPath, [require.resolve('typescript/bin/tsc'), '-p', join(packageRoot, 'tsconfig.build.json')], {
    cwd: packageRoot,
    stdio: 'inherit',
});

// Host half: one ESM file, bare imports resolved by the profile at runtime.
await build({
    entryPoints: [join(packageRoot, 'src/index.ts')],
    outfile: join(libDir, 'index.js'),
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: 'node22',
    packages: 'external',
    sourcemap: false,
    charset: 'utf8',
    logLevel: 'warning',
    banner: { js: '// Generated by scripts/build.ts. Do not edit.' },
});

// Browser half: bundled as the lazy-CJS factory dsh's client loader expects.
const client = await build({
    entryPoints: [join(packageRoot, 'src/client/index.tsx')],
    bundle: true,
    format: 'cjs',
    platform: 'browser',
    target: 'es2022',
    external: ['react', 'react/jsx-runtime'],
    write: false,
    sourcemap: false,
    charset: 'utf8',
    logLevel: 'warning',
});
const bundled = client.outputFiles?.[0]?.text;
if (bundled === undefined) throw new Error('esbuild produced no client bundle');

const wrapped = [
    'window.__ModuleLoader__.load({',
    `\tid: ${JSON.stringify(pkg.name)},`,
    '\tfactory: (require) => {',
    '\t\tvar module = { exports: {} };',
    '\t\tvar exports = module.exports;',
    '\t\tObject.defineProperty(exports, Symbol.toStringTag, { value: "Module" });',
    bundled.trimEnd(),
    '\t\treturn module.exports;',
    '\t}',
    '});',
    '',
].join('\n');
await writeFile(join(libDir, 'client.js'), wrapped);

console.log('built lib/index.js, lib/client.js and lib/types');
